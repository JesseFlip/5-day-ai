export default function SetupPage() {
  const [values, setValues] = useState<Partial<Record<ServiceKey, string>>>({});
  const [statuses, setStatuses] = useState<Record<string, ServiceStatus>>({});
  const [copied, setCopied] = useState(false);

  const allKeys = SERVICES.flatMap((s) => s.keys.map((k) => k.name));
  const filledCount = allKeys.filter((k) => values[k]?.trim()).length;
  const totalCount = allKeys.length;
  const isComplete = filledCount === totalCount;

  function setValue(key: ServiceKey, val: string) {
    setValues((prev) => ({ ...prev, [key]: val }));
  }

  function markService(id: string) {
    const svc = SERVICES.find((s) => s.id === id)!;
    const allFilled = svc.keys.every((k) => values[k.name]?.trim());
    setStatuses((prev) => ({ ...prev, [id]: allFilled ? "entered" : "idle" }));
  }

  function buildEnvFile() {
    const lines = [
      "# Generated by AgentPath /setup",
      "DEMO_MODE=false",
      "SKIP_ENV_VALIDATION=false",
      `MCP_API_KEY=agentpath-mcp-secret-${Date.now()}`,
      "",
    ];
    for (const svc of SERVICES) {
      lines.push(`# ${svc.name}`);
      for (const k of svc.keys) {
        lines.push(`${k.name}=${values[k.name] ?? ""}`);
      }
      lines.push("");
    }
    return lines.join("\n");
  }

  async function copyEnvFile() {
    await navigator.clipboard.writeText(buildEnvFile());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  return (
    <div className="min-h-screen bg-background text-foreground">
      {/* Header */}
      <div className="border-b px-6 py-4 flex items-center gap-4">
        <Link href="/" className="text-sm text-muted-foreground hover:text-foreground">← Back to AgentPath</Link>
        <span className="text-muted-foreground">/</span>
        <span className="font-semibold">Deploy Setup Guide</span>
        <div className="ml-auto text-sm text-muted-foreground">{filledCount}/{totalCount} keys entered</div>
      </div>

      <div className="max-w-2xl mx-auto px-6 py-10 space-y-8">
        {/* Intro */}
        <div>
          <h1 className="text-2xl font-bold mb-2">Set up your own AgentPath</h1>
          <p className="text-muted-foreground">
            You&apos;re currently running in <strong>demo mode</strong> — no database, no auth, no AI calls.
            This guide walks you through getting the 4 services you need to run the full platform.
            All have free tiers. Takes about 10 minutes total.
          </p>
        </div>

        {/* Progress bar */}
        <div className="space-y-1">
          <div className="h-2 rounded-full bg-muted overflow-hidden">
            <div
              className="h-full bg-blue-500 transition-all duration-300"
              style={{ width: `${(filledCount / totalCount) * 100}%` }}
            />
          </div>
          <p className="text-xs text-muted-foreground">{filledCount} of {totalCount} required keys entered</p>
        </div>

        {/* Services */}
        {SERVICES.map((svc) => {
          const status = statuses[svc.id] ?? "idle";
          const svcFilled = svc.keys.filter((k) => values[k.name]?.trim()).length;
          return (
            <div key={svc.id} className={`border rounded-lg p-5 space-y-4 transition-colors ${status === "entered" ? "border-green-500/50 bg-green-500/5" : "border-border"}`}>
              <div className="flex items-start justify-between gap-4">
                <div>
                  <div className="flex items-center gap-2">
                    {status === "entered" && <span className="text-green-500 text-sm font-medium">✓</span>}
                    <h2 className="font-semibold">{svc.name}</h2>
                  </div>
                  <p className="text-sm text-muted-foreground mt-0.5">{svc.description}</p>
                </div>
                <a
                  href={svc.signupUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="shrink-0 text-xs bg-blue-600 text-white px-3 py-1.5 rounded hover:bg-blue-700 transition-colors"
                >
                  Open {svc.name.split(" — ")[0]} →
                </a>
              </div>

              {/* Steps */}
              <ol className="text-sm space-y-1.5 text-muted-foreground">
                {svc.steps.map((step, i) => (
                  <li key={i} className="flex gap-2">
                    <span className="shrink-0 w-5 h-5 rounded-full bg-muted text-xs flex items-center justify-center font-mono">{i + 1}</span>
                    <span>{step}</span>
                  </li>
                ))}
              </ol>

              {/* Key inputs */}
              <div className="space-y-2">
                {svc.keys.map((k) => (
                  <div key={k.name}>
                    <label className="text-xs font-medium text-muted-foreground block mb-1">{k.label}</label>
                    <input
                      type={k.type ?? "text"}
                      placeholder={k.placeholder}
                      value={values[k.name] ?? ""}
                      onChange={(e) => { setValue(k.name, e.target.value); markService(svc.id); }}
                      onBlur={() => markService(svc.id)}
                      className="w-full text-sm font-mono bg-muted border border-border rounded px-3 py-2 focus:outline-none focus:ring-1 focus:ring-blue-500"
                    />
                  </div>
                ))}
              </div>

              <p className="text-xs text-muted-foreground">{svcFilled}/{svc.keys.length} keys for this service</p>
            </div>
          );
        })}

        {/* Output */}
        <div className={`border rounded-lg p-5 space-y-4 transition-colors ${isComplete ? "border-green-500/50" : "border-dashed border-border opacity-60"}`}>
          <h2 className="font-semibold">Your .env.local file</h2>
          {isComplete ? (
            <>
              <p className="text-sm text-muted-foreground">All keys entered. Copy this and save it as <code className="bg-muted px-1 py-0.5 rounded">.env.local</code> in your project root, then run <code className="bg-muted px-1 py-0.5 rounded">pnpm db:push</code> to create the database tables.</p>
              <pre className="text-xs bg-muted rounded p-3 overflow-x-auto whitespace-pre-wrap break-all">{buildEnvFile()}</pre>
              <button
                onClick={copyEnvFile}
                className="bg-green-600 text-white text-sm px-4 py-2 rounded hover:bg-green-700 transition-colors"
              >
                {copied ? "Copied!" : "Copy .env.local"}
              </button>
            </>
          ) : (
            <p className="text-sm text-muted-foreground">Fill in all {totalCount} keys above to generate your .env.local file.</p>
          )}
        </div>

        {/* Next steps */}
        {isComplete && (
          <div className="border rounded-lg p-5 space-y-2">
            <h2 className="font-semibold">Next steps</h2>
            <ol className="text-sm space-y-2 text-muted-foreground">
              <li className="flex gap-2"><span className="shrink-0 font-mono">1.</span> Paste the .env.local content into your project root</li>
              <li className="flex gap-2"><span className="shrink-0 font-mono">2.</span> Run <code className="bg-muted px-1 rounded">pnpm db:push</code> to create database tables</li>
              <li className="flex gap-2"><span className="shrink-0 font-mono">3.</span> Run <code className="bg-muted px-1 rounded">pnpm dev</code> to start the full app (demo mode off)</li>
              <li className="flex gap-2"><span className="shrink-0 font-mono">4.</span> Push to GitHub and connect to Vercel — add the same env vars in Vercel&apos;s dashboard</li>
            </ol>
          </div>
        )}

        <p className="text-xs text-muted-foreground text-center pb-4">
          AgentPath was built by <a href="https://claude.ai/code" className="underline">Claude (Anthropic)</a> via a tool called Lumbergh.
          Not a competition entry — shared freely. Course content © Kaggle &amp; Google.
        </p>
      </div>
    </div>
  );
}
